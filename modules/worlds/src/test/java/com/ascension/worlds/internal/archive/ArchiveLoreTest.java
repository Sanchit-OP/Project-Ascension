package com.ascension.worlds.internal.archive;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.List;
import net.minecraft.network.chat.contents.TranslatableContents;
import org.junit.jupiter.api.Test;

/**
 * The shipped lore, checked against what reads it: every entry the contract promises exists,
 * every key it names has text, and every page fits on vanilla's book page. Text is generated by
 * {@code tools/archive-lore.py}; a page that fails here is cut off mid-sentence in game.
 */
class ArchiveLoreTest {

    /** The eight ids {@code lunar-archive-format.md} promises the design session. */
    private static final List<String> MOON_ENTRIES = List.of(
            "the_road", "the_builders", "many_worlds", "the_keepers",
            "the_quiet", "the_last_order", "the_sealing", "unfinished");

    /**
     * Vanilla's page is 114 px by 128 px: 14 lines of roughly 19 characters in the default font.
     * The first page also carries the bold title and a blank line, three lines in all.
     */
    private static final int PAGE_CHARS = 230;
    private static final int FIRST_PAGE_CHARS = 180;

    @Test
    void everyMoonEntryExistsAndFits() throws IOException {
        JsonObject lang = json("/assets/ascension_worlds_archive/lang/en_us.json").getAsJsonObject();
        for (String name : MOON_ENTRIES) {
            String path = "/data/ascension_worlds/ascension_worlds/archive_entry/moon/" + name + ".json";
            JsonObject entry = json(path).getAsJsonObject();

            assertTrue(lang.has(translateKey(entry.get("title"))), name + ": title has no text");
            var pages = entry.getAsJsonArray("pages");
            assertTrue(pages.size() >= 1, name + ": no pages");
            for (int i = 0; i < pages.size(); i++) {
                String key = translateKey(pages.get(i));
                assertTrue(lang.has(key), name + ": page " + (i + 1) + " has no text");
                int limit = i == 0 ? FIRST_PAGE_CHARS : PAGE_CHARS;
                int length = lang.get(key).getAsString().length();
                assertTrue(length <= limit, name + " page " + (i + 1) + " is " + length + " chars, limit " + limit);
            }
        }
    }

    @Test
    void wornAwayHasText() throws IOException {
        JsonObject lang = json("/assets/ascension_worlds_archive/lang/en_us.json").getAsJsonObject();
        assertTrue(lang.has(((TranslatableContents) ArchiveEntry.WORN_AWAY.getContents()).getKey()));
    }

    @Test
    void storesOnlyHandOutRealEntries() throws IOException {
        String loot = new String(
                resource("/data/ascension_worlds/loot_table/archive/stores.json").readAllBytes(),
                StandardCharsets.UTF_8);
        var matcher = java.util.regex.Pattern.compile("\"ascension_worlds:archive_entry\": \"([^\"]+)\"").matcher(loot);
        int found = 0;
        while (matcher.find()) {
            String id = matcher.group(1);
            String path = id.substring(id.indexOf(':') + 1);
            assertNotNull(getClass().getResource("/data/ascension_worlds/ascension_worlds/archive_entry/" + path + ".json"),
                    "stores hands out unknown entry " + id);
            found++;
        }
        assertEquals(2, found);
    }

    /**
     * The shipped text is all {@code {"translate": key}}. (The real {@code ArchiveEntry.CODEC} needs
     * a bootstrapped game, which plain JUnit cannot give it; a malformed entry fails the datapack
     * registry load loudly at server start instead, which is where it is checked.)
     */
    private static String translateKey(com.google.gson.JsonElement component) {
        return component.getAsJsonObject().get("translate").getAsString();
    }

    private static com.google.gson.JsonElement json(String path) throws IOException {
        try (var reader = new InputStreamReader(resource(path), StandardCharsets.UTF_8)) {
            return JsonParser.parseReader(reader);
        }
    }

    private static java.io.InputStream resource(String path) {
        var stream = ArchiveLoreTest.class.getResourceAsStream(path);
        assertNotNull(stream, "missing " + path);
        return stream;
    }
}
